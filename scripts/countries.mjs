// Writes the phone field's country list (slice D.11b) from the phone metadata
// and CLDR, with no download: every region `libphonenumber-js` knows (owner,
// 2026-11-25), its calling code, and its Arabic and English names from
// Node's ICU (`Intl.DisplayNames`, on the Node pinned in `.node-version`).
// Output: `packages/core_l10n/lib/src/countries.g.dart` (names are user-facing
// words, so they live in core_l10n). `node scripts/countries.mjs --check` fails
// when the committed output differs from a fresh run (ui-web's
// `test/countries.test.ts` runs it; libphonenumber-js is a ui-web dependency).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'packages/ui-web/package.json'));
const { getCountries, getCountryCallingCode } = require('libphonenumber-js/max');

const arabic = new Intl.DisplayNames(['ar'], { type: 'region', fallback: 'code' });
const english = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'code' });

export function countries() {
  return getCountries()
    .map((iso) => ({
      iso,
      code: getCountryCallingCode(iso),
      ar: arabic.of(iso),
      en: english.of(iso),
    }))
    .sort((a, b) => arabicOrder.compare(a.ar, b.ar));
}

// The list is written in Arabic order (CLDR's collation), the order the
// picker shows, so Flutter (no collation of its own) keeps the same order.
const arabicOrder = new Intl.Collator('ar');

const HEADER = 'Generated by scripts/countries.mjs from libphonenumber-js and CLDR; do not edit.';

const dartString = (s) =>
  `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;

export function dart(list) {
  return [
    `// ${HEADER}`,
    '',
    '/// One region of the phone field: ISO code, calling code (no plus), Arabic',
    '/// and English names (CLDR).',
    'typedef FoxCountryName = ({String iso, String code, String ar, String en});',
    '',
    '/// Every region the phone metadata knows, in Arabic order (CLDR).',
    'const foxCountryNames = <FoxCountryName>[',
    // As `dart format` writes it: one line up to 80 columns, else a field per line.
    ...list.map((c) => {
      const fields = [
        `iso: '${c.iso}'`,
        `code: '${c.code}'`,
        `ar: ${dartString(c.ar)}`,
        `en: ${dartString(c.en)}`,
      ];
      const line = `  (${fields.join(', ')}),`;
      return line.length <= 80
        ? line
        : ['  (', ...fields.map((field) => `    ${field},`), '  ),'].join('\n');
    }),
    '];',
    '',
  ].join('\n');
}

export const OUTPUTS = {
  dart: path.join(root, 'packages/core_l10n/lib/src/countries.g.dart'),
};

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const list = countries();
  const outputs = { dart: dart(list) };
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [key, file] of Object.entries(OUTPUTS)) {
    if (!check) {
      writeFileSync(file, outputs[key]);
      console.log(`wrote ${path.relative(root, file)} (${list.length} regions)`);
      continue;
    }
    let current = '';
    try {
      current = readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
    } catch {
      // Missing: stale.
    }
    if (current !== outputs[key]) {
      console.error(`stale: ${path.relative(root, file)} (run node scripts/countries.mjs)`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
}
