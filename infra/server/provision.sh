#!/usr/bin/env bash
# Prepares the shared server for one FOX DROP environment (architecture §17.2),
# as root, from a copy of this repository's infra/ folder:
#   infra/server/provision.sh <environment>
# Safe to run again after a change under infra/nginx or infra/server: it
# reinstalls the configuration and never touches the database, the secrets or
# the releases. The `deploy` skill shows how to run it from a commit on main.
set -euo pipefail

die() {
  echo "provision: $*" >&2
  exit 1
}
step() { printf '\n== %s\n' "$*"; }

environment=${1:-}
[[ $environment =~ ^(staging|production)$ ]] || die "usage: provision.sh staging|production"
[ "$(id -u)" = 0 ] || die "run as root"

infra=$(cd "$(dirname "$0")/.." && pwd)
settings=$infra/environments/$environment.env
[ -f "$settings" ] || die "no $settings"
set -a
# shellcheck source=/dev/null
. "$settings"
set +a

user=foxdrop-$environment
home=/srv/foxdrop-$environment
backups=/var/backups/foxdrop-$environment
acme=/var/www/foxdrop-acme
repository=https://github.com/HussienALfajer/fox-drop.git

step "System users"
# The environment's user owns its files and secrets; containers of the
# server image run as it. It cannot log in and has no sudo.
if ! id "$user" >/dev/null 2>&1; then
  useradd --system --home-dir "$home" --shell /usr/sbin/nologin --user-group "$user"
fi
# The deploy user only receives the deploy key, whose command= allows one
# script (deploy-ssh.sh). It needs a shell for that command to run.
if ! id foxdrop-deploy >/dev/null 2>&1; then
  useradd --create-home --shell /bin/bash --user-group foxdrop-deploy
  passwd --lock foxdrop-deploy >/dev/null
fi
install -d -m 700 -o foxdrop-deploy -g foxdrop-deploy /home/foxdrop-deploy/.ssh
printf 'restrict,command="/usr/local/bin/foxdrop-deploy-ssh" %s\n' "$(cat "$infra/server/deploy-key.pub")" \
  >/home/foxdrop-deploy/.ssh/authorized_keys
chown foxdrop-deploy:foxdrop-deploy /home/foxdrop-deploy/.ssh/authorized_keys
chmod 600 /home/foxdrop-deploy/.ssh/authorized_keys

step "Folders"
install -d -m 750 -o "$user" -g "$user" "$home" "$home/releases" "$home/shared" "$home/shared/db"
install -d -m 700 -o root -g root "$backups"
install -d -m 755 "$acme"
if [ ! -d "$home/repo.git" ]; then
  sudo -u "$user" -H git clone --quiet --mirror "$repository" "$home/repo.git"
fi

step "Secrets"
# Generated here and never printed (architecture §15.4). Hex, so they are
# safe in connection URLs and in the environment file's plain KEY=VALUE form.
env_file=$home/shared/.env
if [ ! -f "$env_file" ]; then
  umask 077
  {
    echo "# FOX DROP $environment secrets: generated by provision.sh, never in the repository."
    echo "POSTGRES_PASSWORD=$(openssl rand -hex 32)"
    echo "FOX_DROP_MIGRATOR_PASSWORD=$(openssl rand -hex 32)"
    echo "FOX_DROP_APP_PASSWORD=$(openssl rand -hex 32)"
    echo "VALKEY_PASSWORD=$(openssl rand -hex 32)"
    echo "IDENTITY_ENCRYPTION_KEY=$(openssl rand -base64 32)"
    echo "# Set by the owner (the deploy skill):"
    echo "SENTRY_DSN="
    echo "B2_ACCOUNT_ID="
    echo "B2_APPLICATION_KEY="
    echo "B2_BUCKET="
    echo "BACKUP_ENCRYPTION_PASSWORD="
  } >"$env_file"
  umask 022
  echo "created $env_file"
fi
chown "$user:$user" "$env_file"
chmod 600 "$env_file"

step "Scripts"
install -m 755 "$infra/server/deploy.sh" /usr/local/bin/foxdrop-deploy
install -m 755 "$infra/server/deploy-ssh.sh" /usr/local/bin/foxdrop-deploy-ssh
install -m 755 "$infra/server/backup.sh" /usr/local/bin/foxdrop-backup
sudoers=$(mktemp)
echo "foxdrop-deploy ALL=(root) NOPASSWD: /usr/local/bin/foxdrop-deploy staging *" >"$sudoers"
visudo --check --quiet --file "$sudoers" || die "the sudoers rule does not parse"
install -m 440 "$sudoers" /etc/sudoers.d/foxdrop-deploy
rm -f "$sudoers"

step "nginx"
# The site relies on the server's own `general` and `perip` zones.
nginx_config=$(nginx -T 2>/dev/null)
for zone in 'zone=general:' 'zone=perip:'; do
  grep -q "$zone" <<<"$nginx_config" || die "the nginx ${zone%:} zone is not defined"
done
# Only these variables are replaced; nginx's own $variables stay as they are.
# shellcheck disable=SC2016
render() { envsubst '${FOXDROP_ENV} ${ADMIN_HOST} ${PORTAL_HOST} ${API_HOST} ${API_PORT} ${ADMIN_PORT} ${PORTAL_PORT}' <"$1"; }
available=/etc/nginx/sites-available/foxdrop-$environment
enabled=/etc/nginx/sites-enabled/foxdrop-$environment
nginx_files=(
  /etc/nginx/conf.d/foxdrop-server-names.conf
  "/etc/nginx/conf.d/foxdrop-$environment-limits.conf"
  /etc/nginx/snippets/foxdrop-proxy.conf
  /etc/nginx/snippets/foxdrop-headers.conf
  "/etc/nginx/snippets/foxdrop-$environment-api.conf"
  "/etc/nginx/snippets/foxdrop-$environment-server.conf"
  "$available"
  "$enabled"
)
saved=$(mktemp -d)
# Installs every FOX DROP nginx file with $1 as the site. If `nginx -t`
# fails, every one of them is put back as it was: one broken file in conf.d or
# sites-enabled takes every site on the server down at the next reload
# (SERVER.md rule 1).
apply_nginx() {
  local file
  rm -rf "${saved:?}"/*
  for file in "${nginx_files[@]}"; do
    if [ -e "$file" ] || [ -L "$file" ]; then cp -P --parents "$file" "$saved"; fi
  done
  install -m 644 "$infra/nginx/server-names.conf" /etc/nginx/conf.d/foxdrop-server-names.conf
  install -m 644 "$infra/nginx/proxy.conf" /etc/nginx/snippets/foxdrop-proxy.conf
  install -m 644 "$infra/nginx/headers.conf" /etc/nginx/snippets/foxdrop-headers.conf
  render "$infra/nginx/limits.conf.template" >"/etc/nginx/conf.d/foxdrop-$environment-limits.conf"
  render "$infra/nginx/api.conf.template" >"/etc/nginx/snippets/foxdrop-$environment-api.conf"
  render "$infra/nginx/server.conf.template" >"/etc/nginx/snippets/foxdrop-$environment-server.conf"
  render "$1" >"$available"
  ln -sfn "$available" "$enabled"
  if ! nginx -t 2>/tmp/foxdrop-nginx-test; then
    for file in "${nginx_files[@]}"; do
      rm -f "$file"
      if [ -e "$saved$file" ] || [ -L "$saved$file" ]; then cp -P "$saved$file" "$file"; fi
    done
    cat /tmp/foxdrop-nginx-test >&2
    die "nginx rejected the configuration; every FOX DROP nginx file was put back as it was"
  fi
  systemctl reload nginx
}
certificate() {
  certbot certonly --webroot -w "$acme" --cert-name "foxdrop-$environment" \
    -d "$ADMIN_HOST" -d "$PORTAL_HOST" -d "$API_HOST" \
    --key-type ecdsa --non-interactive --keep-until-expiring --expand
}
if [ ! -f "/etc/letsencrypt/live/foxdrop-$environment/fullchain.pem" ]; then
  apply_nginx "$infra/nginx/bootstrap.conf.template"
  certificate
fi
apply_nginx "$infra/nginx/site.conf.template"
# Again with the site's port 80 serving the challenges: a no-op until the
# host names change, such as when the domain is bought. The server's renewal
# hook reloads nginx after a renewal; this run reloads it itself.
certificate
systemctl reload nginx
rm -rf "$saved"
echo "site enabled with TLS"

step "fail2ban"
# The nginx jails expand their log globs when they start.
for jail in nginx-4xx-flood nginx-limit-req; do
  if fail2ban-client status "$jail" >/dev/null 2>&1; then
    fail2ban-client reload "$jail" >/dev/null && echo "$jail reloaded"
  fi
done

step "Backup timer"
install -m 644 "$infra/server/foxdrop-backup@.service" "$infra/server/foxdrop-backup@.timer" /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now "foxdrop-backup@$environment.timer"
systemctl list-timers "foxdrop-backup@$environment.timer" --no-pager
