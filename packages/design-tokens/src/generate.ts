// Writes every output of the tokens from the resolved DTCG sources:
//   node src/generate.ts   (pnpm --filter @fox-drop/design-tokens generate)
// The outputs are committed; src/tokens.test.ts fails when one differs from a
// fresh render. Primitives are never exported (architecture §9.5 R1).
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { check, report } from './contrast.ts';
import { designSystem } from './design-system.ts';
import { bakeIcons, dartIcons, readIcons, webIcons } from './icons.ts';
import { isPrimitive, PACKAGE_DIR, resolveAll, type Theme, type Token } from './resolve.ts';

const HEADER = 'Generated by `pnpm --filter @fox-drop/design-tokens generate`. Do not edit.';

type Tokens = Map<string, Token>;

export const exported = (tokens: Tokens) =>
  [...tokens.values()].filter((token) => !isPrimitive(token));
const cssName = (token: Token) => `--fd-${token.path.join('-')}`;
const dimension = (value: unknown) => Number.parseFloat(String(value));

interface Shadow {
  color: string;
  offsetX: string;
  offsetY: string;
  blur: string;
  spread: string;
}

export function cssValue(token: Token): string {
  const { type, value } = token;
  if (type === 'shadow') {
    const s = value as Shadow;
    return `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`;
  }
  if (type === 'cubicBezier') return `cubic-bezier(${(value as number[]).join(', ')})`;
  if (type === 'fontFamily')
    return (value as string[])
      .map((name) => (/^[a-z-]+$/.test(name) ? name : `"${name}"`))
      .join(', ');
  return String(value);
}

const declarations = (tokens: Token[]) =>
  tokens.map((token) => `  ${cssName(token)}: ${cssValue(token)};`).join('\n');

/** The tokens of `theme` whose value differs from `base`. */
function changed(theme: Tokens, base: Tokens): Token[] {
  return exported(theme).filter(
    (token) =>
      JSON.stringify(token.value) !== JSON.stringify(base.get(token.path.join('.'))?.value),
  );
}

export function css(themes: Record<Theme, Tokens>): string {
  const colours = (tokens: Tokens) => exported(tokens).filter((token) => token.type === 'color');
  return [
    `/* ${HEADER} */`,
    '',
    ':root {',
    declarations(exported(themes.light)),
    '}',
    '',
    '/* The dark slot: a copy of the light values until dark mode is designed. */',
    '[data-theme="dark"] {',
    declarations(colours(themes.dark)),
    '}',
    '',
    "/* The captain app: text and numbers at 7:1; orange only on buttons and headings, under the owner's exception. */",
    '[data-surface="captain"] {',
    declarations(changed(themes.captainLight, themes.light)),
    '}',
    '',
    '[data-theme="dark"][data-surface="captain"],',
    '[data-theme="dark"] [data-surface="captain"],',
    '[data-surface="captain"] [data-theme="dark"] {',
    declarations(changed(themes.captainDark, themes.dark)),
    '}',
    '',
  ].join('\n');
}

// Tailwind namespaces for the semantic groups; any other group stays a CSS
// variable only (durations, the component layer).
const TAILWIND: Record<string, string> = {
  color: 'color',
  space: 'spacing',
  radius: 'radius',
  elevation: 'shadow',
  easing: 'ease',
  breakpoint: 'breakpoint',
};

export function tailwind(light: Tokens): string {
  const lines: string[] = [];
  for (const token of exported(light)) {
    const [group, ...rest] = token.path as [string, ...string[]];
    const variable = `var(${cssName(token)})`;
    const namespace = TAILWIND[group];
    // A media query cannot read a variable: breakpoints carry their value.
    const value = group === 'breakpoint' ? cssValue(token) : variable;
    if (namespace) lines.push(`  --${namespace}-${rest.join('-')}: ${value};`);
    else if (group === 'font' && rest[0] === 'family')
      lines.push(`  --font-${rest[1]}: ${variable};`);
    else if (group === 'font' && rest[0] === 'weight')
      lines.push(`  --font-weight-${rest[1]}: ${variable};`);
    else if (group === 'type') {
      const [scale, role, property] = rest;
      const name = `--text-${scale}-${role}`;
      if (property === 'size') lines.push(`  ${name}: ${variable};`);
      if (property === 'line-height') lines.push(`  ${name}--line-height: ${variable};`);
      if (property === 'weight') lines.push(`  ${name}--font-weight: ${variable};`);
    }
  }
  return [
    `/* ${HEADER} */`,
    '/* Tailwind v4 theme: semantic names only, every default removed (architecture §9.5 R1). */',
    '',
    '@theme inline {',
    '  --*: initial;',
    // Preflight and the transition utilities read these defaults.
    '  --default-font-family: var(--fd-font-family-sans);',
    '  --default-transition-duration: var(--fd-duration-base);',
    '  --default-transition-timing-function: var(--fd-easing-standard);',
    ...lines,
    '}',
    '',
  ].join('\n');
}

// Dart ------------------------------------------------------------------

const camel = (parts: string[]) =>
  parts
    .join('-')
    .replace(/^(\d)x/, (_, n: string) => 'x'.repeat(Number(n)))
    .replace(/[-.](\w)/g, (_, c: string) => c.toUpperCase());

/** `#RRGGBB` or `#RRGGBBAA` as a Dart ARGB literal. */
function argb(hex: string): string {
  const rgb = hex.slice(1, 7).toUpperCase();
  const alpha = (hex.slice(7, 9) || 'FF').toUpperCase();
  return `0x${alpha}${rgb}`;
}

const number = (value: number) => (Number.isInteger(value) ? `${value}.0` : `${value}`);

function dartClass(name: string, doc: string, fields: [string, string][]): string {
  return [
    `/// ${doc}`,
    `final class ${name} {`,
    `  const ${name}({`,
    ...fields.map(([field]) => `    required this.${field},`),
    '  });',
    '',
    ...fields.map(([field, type]) => `  final ${type} ${field};`),
    '}',
  ].join('\n');
}

function dartInstance(type: string, name: string, args: [string, string][]): string {
  return [
    `  static const ${type} ${name} = ${type}(`,
    ...args.map(([field, value]) => `    ${field}: ${value},`),
    '  );',
  ].join('\n');
}

const DART_THEMES: Theme[] = ['light', 'dark', 'captainLight', 'captainDark'];

export function dart(themes: Record<Theme, Tokens>): string {
  const light = themes.light;
  const group = (name: string) => exported(light).filter((token) => token.path[0] === name);
  const colourFields = group('color').map((token) => camel(token.path.slice(1)));
  const colourArgs = (tokens: Tokens): [string, string][] =>
    exported(tokens)
      .filter((token) => token.path[0] === 'color')
      .map((token) => [camel(token.path.slice(1)), argb(String(token.value))]);

  // One component's tokens: a class of fields and one instance per theme.
  const component = (name: string, label: string) => {
    const type = `${label}Tokens`;
    const fields = group(name).map((token): [string, string] => [
      camel(token.path.slice(1)),
      token.type === 'color' ? 'int' : 'double',
    ]);
    const args = (tokens: Tokens): [string, string][] =>
      exported(tokens)
        .filter((token) => token.path[0] === name)
        .map((token) => [
          camel(token.path.slice(1)),
          token.type === 'color' ? argb(String(token.value)) : number(dimension(token.value)),
        ]);
    return [
      dartClass(type, `The ${label} component tokens of one theme.`, fields),
      '',
      `/// The ${label} tokens per theme.`,
      `abstract final class Fox${label} {`,
      DART_THEMES.map((theme) => dartInstance(type, theme, args(themes[theme]))).join('\n\n'),
      '}',
    ].join('\n');
  };

  const constants = (name: string, doc: string, type: string, value: (t: Token) => string) =>
    [
      `/// ${doc}`,
      `abstract final class ${name} {`,
      ...group(name.replace(/^Fox/, '').toLowerCase()).map(
        (token) => `  static const ${type} ${camel(token.path.slice(1))} = ${value(token)};`,
      ),
      '}',
    ].join('\n');

  const shadows = group('elevation').map((token) => {
    const s = token.value as Shadow;
    return dartInstance('ShadowToken', camel(token.path.slice(1)), [
      ['color', argb(s.color)],
      ['offsetX', number(dimension(s.offsetX))],
      ['offsetY', number(dimension(s.offsetY))],
      ['blur', number(dimension(s.blur))],
      ['spread', number(dimension(s.spread))],
    ]);
  });

  const scales = [...new Set(group('type').map((token) => token.path[1]!))];
  const roles = [...new Set(group('type').map((token) => token.path[2]!))];
  const role = (scale: string, name: string) => {
    const get = (property: string) => light.get(`type.${scale}.${name}.${property}`)!.value;
    return `TypeRole(size: ${number(dimension(get('size')))}, lineHeight: ${number(Number(get('line-height')))}, weight: ${String(get('weight'))})`;
  };
  const [family] = light.get('font.family.sans')!.value as string[];
  const easing = (light.get('easing.standard')!.value as number[]).map(number).join(', ');

  return [
    `// ${HEADER}`,
    '// Architecture §9.2; brand expression §3, §6, §7.',
    '',
    dartClass('ColorTokens', 'The semantic colours of one theme, as ARGB.', [
      ...colourFields.map((field): [string, string] => [field, 'int']),
    ]),
    '',
    '/// The semantic colours per theme. Dark holds a copy of light for now.',
    'abstract final class FoxColors {',
    DART_THEMES.map((theme) => dartInstance('ColorTokens', theme, colourArgs(themes[theme]))).join(
      '\n\n',
    ),
    '}',
    '',
    component('button', 'Button'),
    '',
    component('input', 'Input'),
    '',
    constants('FoxSpace', 'The spacing steps of the 4-point grid.', 'double', (t) =>
      number(dimension(t.value)),
    ),
    '',
    constants('FoxRadius', 'Corner radii.', 'double', (t) => number(dimension(t.value))),
    '',
    constants(
      'FoxDuration',
      'Motion durations (brand expression §3).',
      'Duration',
      (t) => `Duration(milliseconds: ${dimension(t.value)})`,
    ),
    '',
    '/// The calm easing, without bounce, as cubic Bézier control points.',
    'abstract final class FoxEasing {',
    `  static const List<double> standard = [${easing}];`,
    '}',
    '',
    dartClass('ShadowToken', 'One elevation shadow; the colour is ARGB.', [
      ['color', 'int'],
      ['offsetX', 'double'],
      ['offsetY', 'double'],
      ['blur', 'double'],
      ['spread', 'double'],
    ]),
    '',
    '/// The elevation shadows.',
    'abstract final class FoxElevation {',
    shadows.join('\n\n'),
    '}',
    '',
    '/// The UI typeface and its weights (brand expression §7).',
    'abstract final class FoxFont {',
    `  static const String family = '${family}';`,
    ...group('font')
      .filter((token) => token.path[1] === 'weight')
      .map((token) => `  static const int ${token.path[2]} = ${String(token.value)};`),
    '}',
    '',
    dartClass('TypeRole', 'One role of a type scale.', [
      ['size', 'double'],
      ['lineHeight', 'double'],
      ['weight', 'int'],
    ]),
    '',
    dartClass(
      'TypeScale',
      'The type scale of one surface.',
      roles.map((name): [string, string] => [camel([name]), 'TypeRole']),
    ),
    '',
    '/// The type scale per surface (brand expression §7).',
    'abstract final class FoxType {',
    scales
      .map((scale) =>
        dartInstance(
          'TypeScale',
          scale,
          roles.map((name): [string, string] => [camel([name]), role(scale, name)]),
        ),
      )
      .join('\n\n'),
    '}',
    '',
    '/// Sizes.',
    'abstract final class FoxSize {',
    ...group('size').map(
      (token) =>
        `  static const double ${camel(token.path.slice(1))} = ${number(dimension(token.value))};`,
    ),
    '}',
    '',
  ].join('\n');
}

export const OUTPUTS = {
  css: 'generated/tokens.css',
  tailwind: 'generated/tailwind.css',
  report: 'generated/contrast-report.md',
  dart: '../core_tokens/lib/src/tokens.g.dart',
  designSystem: 'generated/design-system.json',
  webIcons: 'generated/icons.ts',
  dartIcons: '../core_tokens/lib/src/icons.g.dart',
} as const;

export async function render(): Promise<Record<keyof typeof OUTPUTS, string>> {
  const themes = await resolveAll();
  const icons = await bakeIcons(readIcons());
  return {
    webIcons: webIcons(icons),
    dartIcons: dartIcons(icons),
    css: css(themes),
    tailwind: tailwind(themes.light),
    report: report(check(themes)),
    dart: dart(themes),
    designSystem: designSystem(themes),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputs = await render();
  for (const [key, file] of Object.entries(OUTPUTS)) {
    const target = path.join(PACKAGE_DIR, file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, outputs[key as keyof typeof OUTPUTS]);
    console.log(`wrote ${file}`);
  }
}
