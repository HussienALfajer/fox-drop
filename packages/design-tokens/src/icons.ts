// The icon set's outputs (architecture §9.4; brand expression §10): set v4
// "Madar". Each source in icons/ is a list of <path> elements carrying their
// role; the outputs carry the elements for Linear, Duotone and Brand Duo, and
// the baked Broken, Bold and Bold Duo of src/icon-bake.ts, so the web and
// Flutter draw path data only. Written by src/generate.ts with the tokens.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { bakeIcon, loadSkia, WEIGHTS, type Baked, type Element, type Layer } from './icon-bake.ts';
import { parseIcon } from './icon-geometry.ts';
import { PACKAGE_DIR } from './resolve.ts';

const HEADER = 'Generated by `pnpm --filter @fox-drop/design-tokens generate`. Do not edit.';

export const ICONS_DIR = path.join(PACKAGE_DIR, 'icons');

export interface IconEntry {
  name: string;
  group: string;
  mirror: boolean;
  description: string;
}

export interface Icon extends IconEntry {
  source: string;
  elements: Element[];
  /** The Linear path data, one string per element. */
  paths: string[];
}

export type BakedIcon = Icon & Baked;

/** The six styles (§9.4), in the order of the Madar sheet. */
export const STYLES = ['linear', 'duotone', 'brand-duo', 'broken', 'bold', 'bold-duo'] as const;
export type IconStyle = (typeof STYLES)[number];

/** The stroke of every style but Bold and Bold Duo, on the phone and the web. */
export const STROKE = WEIGHTS[0];

function element(attributes: Record<string, string>): Element {
  const flag = (key: string) => attributes[`data-${key}`] === 'true';
  return {
    d: attributes.d!,
    role: attributes['data-role'] as Element['role'],
    ...(attributes['data-knock'] ? { knock: attributes['data-knock'] as Element['knock'] } : {}),
    accent: flag('accent'),
    fill: flag('fill'),
    open: flag('open'),
    halo: flag('halo'),
  };
}

/** The set in the manifest's order, each with its source and elements. */
export function readIcons(): Icon[] {
  const manifest = JSON.parse(
    readFileSync(path.join(ICONS_DIR, 'icons.json'), 'utf8'),
  ) as IconEntry[];
  return manifest.map((entry) => {
    const source = readFileSync(path.join(ICONS_DIR, `${entry.name}.svg`), 'utf8');
    const elements = parseIcon(source).shapes.map((shape) => element(shape.attributes));
    return { ...entry, source, elements, paths: elements.map((e) => e.d) };
  });
}

/** The set with its baked styles. */
export async function bakeIcons(icons: Icon[]): Promise<BakedIcon[]> {
  const ck = await loadSkia();
  return icons.map((icon) => ({ ...icon, ...bakeIcon(ck, icon.elements) }));
}

/**
 * The inside of a 24-grid <svg> for one style, for the review sheets:
 * strokes for the line styles, fills for the bold ones.
 */
export function styleMarkup(icon: BakedIcon, style: IconStyle, ink: string, brand: string): string {
  const line = (inner: string) =>
    `<g fill="none" stroke="${ink}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">${inner}</g>`;
  const fill = (layers: Layer[]) =>
    `<g fill="${ink}">${layers.map((l) => `<path d="${l.d}"${l.faded ? ' fill-opacity="0.5"' : ''}/>`).join('')}</g>`;
  switch (style) {
    case 'linear':
      return line(icon.paths.map((d) => `<path d="${d}"/>`).join(''));
    case 'duotone':
      return line(
        icon.elements
          .map((e) => `<path d="${e.d}"${e.accent ? '' : ' opacity="0.5"'}/>`)
          .join(''),
      );
    case 'brand-duo':
      return line(
        icon.elements
          .map((e) => `<path d="${e.d}"${e.accent ? ` stroke="${brand}"` : ''}/>`)
          .join(''),
      );
    case 'broken':
      return line(icon.broken.map((d) => `<path d="${d}"/>`).join(''));
    case 'bold':
      return fill(icon.bold[STROKE]);
    case 'bold-duo':
      return fill(icon.boldDuo[STROKE]);
  }
}

const camel = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const quote = (d: string) => `'${d}'`;

export function webIcons(icons: BakedIcon[]): string {
  const layers = (list: Layer[]) =>
    `[${list.map((l) => `{ d: ${quote(l.d)}, faded: ${l.faded} }`).join(', ')}]`;
  const body = icons.map((icon) =>
    [
      `  /** ${icon.description} */`,
      `  '${icon.name}': {`,
      `    elements: [${icon.elements.map((e) => `{ d: ${quote(e.d)}, accent: ${e.accent} }`).join(', ')}],`,
      `    broken: [${icon.broken.map(quote).join(', ')}],`,
      `    bold: ${layers(icon.bold[STROKE])},`,
      `    boldDuo: ${layers(icon.boldDuo[STROKE])},`,
      `    mirror: ${icon.mirror},`,
      '  },',
    ].join('\n'),
  );
  return [
    `// ${HEADER}`,
    '// Architecture §9.4; brand expression §10. Set v4 "Madar" on the 24 grid.',
    '// `elements` are stroked in currentColor at 1.5 with round caps and joins',
    '// (Linear; Duotone fades the non-accent ones to 0.5; Brand Duo strokes the',
    '// accent in the brand colour). `broken` is stroked the same way. `bold` and',
    '// `boldDuo` are fills, the faded layers at 0.5. `mirror` icons flip',
    '// horizontally in right-to-left layouts.',
    '',
    'export const icons = {',
    ...body,
    '} as const;',
    '',
    'export type IconName = keyof typeof icons;',
    '',
  ].join('\n');
}

// Dart, in `dart format` style: a call or a list stays on one line when it
// fits in 80 columns, else each item goes on its own line.
const WIDTH = 80;

function call(indent: string, head: string, args: string[], tail: string): string[] {
  const one = `${indent}${head}(${args.join(', ')})${tail}`;
  if (one.length <= WIDTH) return [one];
  return [`${indent}${head}(`, ...args.map((a) => `${indent}  ${a},`), `${indent})${tail}`];
}

function list(indent: string, head: string, items: string[][], tail: string): string[] {
  const flat = items.every((item) => item.length === 1);
  if (flat) {
    const one = `${indent}${head}[${items.map((item) => item[0]!.trim()).join(', ')}]${tail}`;
    if (one.length <= WIDTH) return [one];
  }
  return [`${indent}${head}[`, ...items.flat(), `${indent}]${tail}`];
}

function dartLayers(indent: string, head: string, layers: Layer[]): string[] {
  return list(
    indent,
    head,
    layers.map((l) =>
      call(`${indent}  `, 'FoxIconLayer', [quote(l.d), ...(l.faded ? ['faded: true'] : [])], ','),
    ),
    ',',
  );
}

export function dartIcons(icons: BakedIcon[]): string {
  const [phone, captain] = WEIGHTS;
  const body = icons.map((icon) => {
    const i = '    ';
    const lines = [
      ...list(
        i,
        'elements: ',
        icon.elements.map((e) =>
          call(`${i}  `, 'FoxIconElement', [quote(e.d), ...(e.accent ? ['accent: true'] : [])], ','),
        ),
        ',',
      ),
      ...list(
        i,
        'broken: ',
        icon.broken.map((d) => [`${i}  ${quote(d)},`]),
        ',',
      ),
      ...dartLayers(i, 'bold: ', icon.bold[phone]),
      ...dartLayers(i, 'boldCaptain: ', icon.bold[captain]),
      ...dartLayers(i, 'boldDuo: ', icon.boldDuo[phone]),
      ...dartLayers(i, 'boldDuoCaptain: ', icon.boldDuo[captain]),
      ...(icon.mirror ? [`${i}mirror: true,`] : []),
    ];
    return [
      `  /// ${icon.description}`,
      `  static const ${camel(icon.name)} = FoxIconData(`,
      ...lines,
      '  );',
    ].join('\n');
  });
  return [
    `// ${HEADER}`,
    '// Architecture §9.4; brand expression §10.',
    '',
    '/// The stroke weights the icons are baked at (`icon-stroke.*`).',
    'enum FoxIconWeight {',
    '  /// The customer and restaurant apps, and the web.',
    `  phone(${phone}),`,
    '',
    '  /// The captain app.',
    `  captain(${captain});`,
    '',
    '  const FoxIconWeight(this.stroke);',
    '',
    '  /// The stroke width on the 24 grid.',
    '  final double stroke;',
    '}',
    '',
    '/// One element of an icon: SVG path data on the 24 grid, stroked with round',
    '/// caps and joins.',
    'final class FoxIconElement {',
    '  const FoxIconElement(this.d, {this.accent = false});',
    '',
    '  final String d;',
    '',
    '  /// The meaning layer: in the brand colour in Brand Duo, full ink in',
    '  /// Duotone.',
    '  final bool accent;',
    '}',
    '',
    '/// One fill layer of Bold or Bold Duo: SVG path data, filled nonzero.',
    'final class FoxIconLayer {',
    '  const FoxIconLayer(this.d, {this.faded = false});',
    '',
    '  final String d;',
    '',
    '  /// Drawn at half opacity.',
    '  final bool faded;',
    '}',
    '',
    '/// One icon of set v4 "Madar" in its six styles: the elements (Linear,',
    '/// Duotone, Brand Duo), Broken as stroked path data, and Bold and Bold Duo',
    '/// as fills baked at each [FoxIconWeight].',
    'final class FoxIconData {',
    '  const FoxIconData({',
    '    required this.elements,',
    '    required this.broken,',
    '    required List<FoxIconLayer> bold,',
    '    required List<FoxIconLayer> boldCaptain,',
    '    required List<FoxIconLayer> boldDuo,',
    '    required List<FoxIconLayer> boldDuoCaptain,',
    '    this.mirror = false,',
    '  }) : _bold = bold,',
    '       _boldCaptain = boldCaptain,',
    '       _boldDuo = boldDuo,',
    '       _boldDuoCaptain = boldDuoCaptain;',
    '',
    '  final List<FoxIconElement> elements;',
    '',
    '  /// The elements with the primary body bitten once (Broken).',
    '  final List<String> broken;',
    '',
    '  final List<FoxIconLayer> _bold;',
    '  final List<FoxIconLayer> _boldCaptain;',
    '  final List<FoxIconLayer> _boldDuo;',
    '  final List<FoxIconLayer> _boldDuoCaptain;',
    '',
    '  /// Whether the icon flips horizontally under a right-to-left',
    '  /// `Directionality`.',
    '  final bool mirror;',
    '',
    '  /// Bold at [weight]: one opaque fill.',
    '  List<FoxIconLayer> bold(FoxIconWeight weight) => switch (weight) {',
    '    FoxIconWeight.phone => _bold,',
    '    FoxIconWeight.captain => _boldCaptain,',
    '  };',
    '',
    '  /// Bold Duo at [weight]: the non-accent bodies faded.',
    '  List<FoxIconLayer> boldDuo(FoxIconWeight weight) => switch (weight) {',
    '    FoxIconWeight.phone => _boldDuo,',
    '    FoxIconWeight.captain => _boldDuoCaptain,',
    '  };',
    '}',
    '',
    '/// The icon set, in the order of brand expression §10.',
    'abstract final class FoxIcons {',
    body.join('\n\n'),
    '',
    '  /// Every icon by its name in the sources.',
    '  static const all = <String, FoxIconData>{',
    ...icons.map((icon) => `    '${icon.name}': ${camel(icon.name)},`),
    '  };',
    '}',
    '',
  ].join('\n');
}
