// The icon set's outputs (architecture §9.4; brand expression §10): every
// shape of every source in icons/ normalised to SVG path data, so the web and
// Flutter read paths only. Written by src/generate.ts with the tokens.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { parseIcon, type Shape } from './icon-geometry.ts';
import { PACKAGE_DIR } from './resolve.ts';

const HEADER = 'Generated by `pnpm --filter @fox-drop/design-tokens generate`. Do not edit.';

export const ICONS_DIR = path.join(PACKAGE_DIR, 'icons');

export interface IconEntry {
  name: string;
  group: string;
  mirror: boolean;
  description: string;
}

export interface Icon extends IconEntry {
  source: string;
  paths: string[];
}

const fixed = (value: number) => String(Number(value.toFixed(2)));

function points(text: string): string {
  const values = (text.match(/[-+]?(?:\d+\.?\d*|\.\d+)/g) ?? []).map(Number);
  const pairs: string[] = [];
  for (let i = 0; i < values.length; i += 2)
    pairs.push(`${fixed(values[i]!)} ${fixed(values[i + 1]!)}`);
  return pairs.join('L');
}

/** One shape as path data. */
export function toPath({ name, attributes: a }: Shape): string {
  const n = (key: string) => Number(a[key] ?? 0);
  switch (name) {
    case 'path':
      return a.d!;
    case 'circle':
    case 'ellipse': {
      const rx = name === 'circle' ? n('r') : n('rx');
      const ry = name === 'circle' ? n('r') : n('ry');
      const arc = `A${fixed(rx)} ${fixed(ry)} 0 1 0`;
      const left = `${fixed(n('cx') - rx)} ${fixed(n('cy'))}`;
      return `M${left}${arc} ${fixed(n('cx') + rx)} ${fixed(n('cy'))}${arc} ${left}Z`;
    }
    case 'line':
      return `M${fixed(n('x1'))} ${fixed(n('y1'))}L${fixed(n('x2'))} ${fixed(n('y2'))}`;
    case 'polyline':
      return `M${points(a.points!)}`;
    case 'polygon':
      return `M${points(a.points!)}Z`;
    case 'rect': {
      const [x, y, w, h] = [n('x'), n('y'), n('width'), n('height')];
      const rx = Math.min(n('rx') || n('ry'), w / 2);
      const ry = Math.min(n('ry') || n('rx'), h / 2);
      if (!rx || !ry) return `M${fixed(x)} ${fixed(y)}h${fixed(w)}v${fixed(h)}h${fixed(-w)}Z`;
      const corner = (dx: number, dy: number) =>
        `a${fixed(rx)} ${fixed(ry)} 0 0 1 ${fixed(dx)} ${fixed(dy)}`;
      return [
        `M${fixed(x + rx)} ${fixed(y)}`,
        `h${fixed(w - 2 * rx)}`,
        corner(rx, ry),
        `v${fixed(h - 2 * ry)}`,
        corner(-rx, ry),
        `h${fixed(-(w - 2 * rx))}`,
        corner(-rx, -ry),
        `v${fixed(-(h - 2 * ry))}`,
        corner(rx, -ry),
        'Z',
      ].join('');
    }
    default:
      throw new Error(`<${name}> is not a shape element`);
  }
}

/** The set in the manifest's order, each with its source and path data. */
export function readIcons(): Icon[] {
  const manifest = JSON.parse(
    readFileSync(path.join(ICONS_DIR, 'icons.json'), 'utf8'),
  ) as IconEntry[];
  return manifest.map((entry) => {
    const source = readFileSync(path.join(ICONS_DIR, `${entry.name}.svg`), 'utf8');
    return { ...entry, source, paths: parseIcon(source).shapes.map(toPath) };
  });
}

const camel = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

export function webIcons(icons: Icon[]): string {
  const body = icons.map((icon) =>
    [
      `  /** ${icon.description} */`,
      `  '${icon.name}': {`,
      `    d: [${icon.paths.map((d) => `'${d}'`).join(', ')}],`,
      `    mirror: ${icon.mirror},`,
      '  },',
    ].join('\n'),
  );
  return [
    `// ${HEADER}`,
    '// Architecture §9.4; brand expression §10. Each icon is SVG path data on the',
    '// 24 grid, stroked in currentColor at 2/24 of the size with round caps and',
    '// joins; `mirror` icons flip horizontally in right-to-left layouts.',
    '',
    'export const icons = {',
    ...body,
    '} as const;',
    '',
    'export type IconName = keyof typeof icons;',
    '',
  ].join('\n');
}

export function dartIcons(icons: Icon[]): string {
  // In `dart format` style: one line when it fits in 80 columns.
  const body = icons.map((icon) => {
    const head = `  static const ${camel(icon.name)} = FoxIconData([`;
    const tail = icon.mirror ? '], mirror: true);' : ']);';
    const line = `${head}${icon.paths.map((d) => `'${d}'`).join(', ')}${tail}`;
    return [
      `  /// ${icon.description}`,
      ...(line.length <= 80
        ? [line]
        : [head, ...icon.paths.map((d) => `    '${d}',`), `  ${tail}`]),
    ].join('\n');
  });
  return [
    `// ${HEADER}`,
    '// Architecture §9.4; brand expression §10.',
    '',
    '/// One icon: SVG path data on the 24 grid, stroked at 2/24 of the size with',
    '/// round caps and joins.',
    'final class FoxIconData {',
    '  const FoxIconData(this.paths, {this.mirror = false});',
    '',
    '  /// The outline, one SVG path data string per shape.',
    '  final List<String> paths;',
    '',
    '  /// Whether the icon flips horizontally under a right-to-left',
    '  /// `Directionality`.',
    '  final bool mirror;',
    '}',
    '',
    '/// The first icon set, in the order of brand expression §10.',
    'abstract final class FoxIcons {',
    body.join('\n\n'),
    '',
    '  /// Every icon by its name in the sources.',
    '  static const all = <String, FoxIconData>{',
    ...icons.map((icon) => `    '${icon.name}': ${camel(icon.name)},`),
    '  };',
    '}',
    '',
  ].join('\n');
}
